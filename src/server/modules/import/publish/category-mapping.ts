// ── Resolver ──────────────────────────────────────────────────────────────────

function normalizeForLookup(s: string): string {
  return s.toLowerCase().replace(/\s+/g, " ").trim();
}

/**
 * Найти допустимую категорию Place из списка кандидатов.
 *
 * Порядок:
 *   1. Точное совпадение с ALLOWED_CATEGORIES (case-insensitive)
 *   2. Совпадение через ALIAS_MAP
 *
 * Возвращает первый найденный валидный маппинг или null.
 */
export function resolveAllowedCategory(candidates: string[]): AllowedCategory | null {
  for (const raw of candidates) {
    const normalized = normalizeForLookup(raw);

    // 1. Точное совпадение
    const exact = ALLOWED_CATEGORIES.find(
      (c) => normalizeForLookup(c) === normalized,
    );
    if (exact) return exact;

    // 2. Alias lookup
    const alias = ALIAS_MAP[normalized];
    if (alias) return alias;
  }
  return null;
}
