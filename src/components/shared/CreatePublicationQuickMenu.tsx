/**
 * Кнопка «+» и модалка выбора.
 * `full` — бизнес-сценарии и административные публикации; `business` — только бизнес-сценарии.
 * `trigger` — кастомный триггер вместо стандартной кнопки «+».
 */
export function CreatePublicationQuickMenu({
  publicationMode = "full",
  trigger: customTrigger,
}: {
  publicationMode?: PublicationMode;
  trigger?: (onClick: () => void) => React.ReactNode;
}) {
  const router = useRouter();
  const pathname = usePathname();
  const searchParams = useSearchParams();
  const [open, setOpen] = useState(false);
  const hydrated = useHydrated();
  const isMobile = useMediaQuery("(max-width: 1023px)");

  const currentSurfaceReturnTo = useMemo(() => {
    if (!hydrated) {
      return null;
    }

    const host = window.location.host;
    const surface = resolveSurfaceFromHostAndPathname(host, pathname);
    const search = searchParams?.toString();
    const visiblePath = `${pathname}${search ? `?${search}` : ""}`;

    if (surface === "admin") {
      return buildAdminPath(normalizeTargetPathForSurface("admin", visiblePath));
    }

    if (surface === "business") {
      return buildBusinessPath(normalizeTargetPathForSurface("business", visiblePath));
    }

    return null;
  }, [hydrated, pathname, searchParams]);

  const visibleItems = publicationMode === "full"
    ? [...BUSINESS_INTENTS, ...ADMIN_ONLY_ITEMS]
    : BUSINESS_OFFERS_ENABLED
      ? BUSINESS_INTENTS
      : BUSINESS_INTENTS.filter((item) => item.id === "dated-event" || item.id === "visit-place");

  const goAdminPublication = (type: "news" | "article" | "collection") => {
    setOpen(false);
    if (type === "article") {
      router.push("/admin/content/articles/new");
    } else {
      router.push(`/admin/content/publications/new?type=${type}`);
    }
  };

  const renderItems = () => (
    <div className="grid max-h-[min(70dvh,32rem)] gap-2 overflow-y-auto overscroll-contain px-4 pb-4 pt-2">
      {visibleItems.map((item) => {
        const { Icon } = item;
        const rowClass =
          "flex items-start gap-3 rounded-lg border border-gray-200 bg-white p-4 text-left transition-colors hover:bg-gray-50 hover:border-gray-300";
        const isBusinessIntent = BUSINESS_INTENTS.some(intent => intent.id === item.id);
        const itemRowClass = cn(rowClass, isBusinessIntent && "min-h-[104px] items-center");

        if (item.kind === "link") {
          const href = (() => {
            if (!currentSurfaceReturnTo) {
              return item.href;
            }

            const params = new URLSearchParams();
            params.set("returnTo", currentSurfaceReturnTo);
            const separator = item.href.includes("?") ? "&" : "?";
            return `${item.href}${separator}${params.toString()}`;
          })();

          return (
            <Fragment key={item.id}>
              {item.id === "visit-place" && publicationMode === "full" && (
                <div role="separator" aria-orientation="horizontal" className="my-2 border-t border-border" />
              )}
              <Link
                href={href}
                onClick={() => setOpen(false)}
                className={itemRowClass}
              >
                <span className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-primary/10 text-primary">
                  <Icon className="h-5 w-5" />
                </span>
                <span className="min-w-0">
                  <span className="block text-[14px] font-semibold text-gray-900">
                    {item.label}
                  </span>
                  {item.description ? (
                    <span className={cn("block text-[12px] text-muted-foreground", isBusinessIntent && "line-clamp-2 min-h-10 max-w-[260px] leading-5")}>
                      {item.description}
                    </span>
                  ) : null}
                </span>
              </Link>
            </Fragment>
          );
        }

        return (
          <Fragment key={item.id}>
            {publicationMode === "full" && item.id === "news" && (
              <div role="separator" aria-orientation="horizontal" className="my-2 border-t border-border" />
            )}
          <button
            type="button"
            onClick={() => goAdminPublication(item.publicationType)}
            className={cn(itemRowClass, "w-full")}
          >
            <span className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-primary/10 text-primary">
              <Icon className="h-5 w-5" />
            </span>
            <span className="min-w-0 text-left">
              <span className="block text-[14px] font-semibold text-gray-900">
                {item.label}
              </span>
              {item.description ? (
                <span className={cn("block text-[12px] text-muted-foreground", isBusinessIntent && "line-clamp-2 min-h-10 max-w-[260px] leading-5")}>
                  {item.description}
                </span>
              ) : null}
            </span>
          </button>
          </Fragment>
        );
      })}
    </div>
  );

  return (
    <>
      {customTrigger ? (
        customTrigger(() => setOpen(true))
      ) : (
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className={cn(HEADER_CHROME_ICON_BUTTON_CLASS)}
          onClick={() => setOpen(true)}
          aria-label={publicationMode === "business" ? "Добавить" : "Создать публикацию"}
        >
          <Plus className="h-4 w-4" />
        </Button>
      )}

      {isMobile ? (
        <BottomSheet
          open={open}
          onOpenChange={setOpen}
          title="Что хотите добавить?"
          showCloseButton={true}
          height="min(85dvh, 720px)"
        >
          {renderItems()}
        </BottomSheet>
      ) : (
        <Dialog open={open} onOpenChange={setOpen}>
          <DialogContent className="sm:max-w-md">
            <DialogHeader>
              <DialogTitle>Что хотите добавить?</DialogTitle>
              <DialogDescription>
                Выберите понятный формат. Даты и детали уточним при заполнении.
              </DialogDescription>
            </DialogHeader>
            {renderItems()}
          </DialogContent>
        </Dialog>
      )}
    </>
  );
}
