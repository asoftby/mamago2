import { useHydrated } from "@/hooks/use-hydrated";
import { useMediaQuery } from "@/hooks/useMediaQuery";
import {
  buildAdminPath,
  buildBusinessPath,
  normalizeTargetPathForSurface,
  resolveSurfaceFromHostAndPathname,
} from "@/lib/routing/surface";

type PublicationMode = "full" | "business";

type Item =
  | {
      id: string;
      label: string;
      description?: string;
      Icon: LucideIcon;
      kind: "link";
      href: string;
    }
  | {
      id: string;
      label: string;
      description?: string;
      Icon: LucideIcon;
      kind: "admin";
      publicationType: "news" | "article" | "collection";
    };

const ADMIN_ONLY_ITEMS: Item[] = [
  {
    id: "news",
    kind: "admin",
    publicationType: "news",
    label: "Breaking news",
    description: "Короткий формат",
    Icon: Newspaper,
  },
  {
    id: "article",
    kind: "admin",
    publicationType: "article",
    label: "Статья или обзор",
    description: "Полноценная статья",
    Icon: FileText,
  },
  {
    id: "collection",
    kind: "admin",
    publicationType: "collection",
    label: "Подборка",
    description: "Тематическая подборка с лентой",
    Icon: Layers,
  },
];

/**
 * Business-facing intents, rather than internal Event/Offer model names.
 * The destination editors remain the single write paths. No duplicate
 * events, offers or places are generated by this menu.
 */
